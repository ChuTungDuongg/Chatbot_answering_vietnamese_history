import { Buffer } from "node:buffer";
import { test, expect } from "@playwright/test";

test("v1.1 experiment, blind review, comparison and import preview", async ({page}, testInfo) => {
  expect((await page.request.get("/api/v1/eval/experiments")).status()).toBe(401);
  await page.goto("/login");
  expect(await page.evaluate(async()=> (await fetch("/auth/login", {method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({password:"test-password"})})).status)).toBe(200);
  const version=`v11-${testInfo.project.name}`;
  expect(await page.evaluate(async version => (await fetch("/api/v1/eval/snapshots", {method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({version})})).status,version)).toBe(201);
  await page.goto("/eval-studio");
  await page.getByRole("navigation").getByRole("button",{name:"Experiments"}).click();
  for (const model of ["Luna","Terra"]) {
    await page.getByRole("button",{name:"Tạo experiment"}).click();
    await page.getByLabel("Tên experiment").fill(`${model} ${testInfo.project.name}`);
    await page.getByLabel("Dataset snapshot").selectOption(version);
    await page.getByLabel("Model ID").fill(model);
    await page.getByRole("button",{name:"Lưu experiment"}).click();
    await expect(page.getByText("Đã tạo experiment gắn với snapshot bất biến.")).toBeVisible();
    await page.getByLabel("Question ID trong snapshot").fill("HIST-EVAL-001");
    await page.getByLabel("Model output").fill(`Output ${model}`);
    await page.getByRole("button",{name:"Lưu run"}).click();
    await expect(page.getByText("Đã lưu run và output.")).toBeVisible();
  }
  await page.getByRole("navigation").getByRole("button",{name:"Blind A/B"}).click();
  await page.getByLabel("Dataset snapshot").selectOption(version);
  await page.getByLabel("Experiment 1").selectOption({label:`Luna ${testInfo.project.name}`});
  await page.getByLabel("Experiment 2").selectOption({label:`Terra ${testInfo.project.name}`});
  await page.getByRole("button",{name:"Tạo phiên"}).click();
  await expect(page.getByText("RESPONSE A")).toBeVisible();
  await expect(page.getByText("RESPONSE B")).toBeVisible();
  await expect(page.getByRole("button",{name:"Reveal identity"})).toHaveCount(0);
  for(const side of ["A","B"]) for(const label of ["Historical Accuracy","Coverage","Reasoning Depth","Evidence & Citation","Clarity & Structure"]) await page.getByLabel(`Điểm ${side} ${label}`).selectOption("4");
  await page.getByLabel("Ưu tiên").selectOption("tie");
  await page.getByRole("button",{name:"Lưu đánh giá blind"}).click();
  await page.getByRole("button",{name:"Reveal identity"}).click();
  await expect(page.getByText(new RegExp(`A · (Luna|Terra) ${testInfo.project.name}`))).toBeVisible();
  await page.reload();
  await page.getByRole("navigation").getByRole("button",{name:"Blind A/B"}).click();
  await page.getByRole("button",{name:/Phiên/}).first().click();
  await expect(page.getByRole("button",{name:"Reveal identity"})).toBeVisible();
  await page.getByRole("navigation").getByRole("button",{name:"Model Comparison"}).click();
  await page.getByLabel("Dataset snapshot").selectOption(version);
  await page.getByLabel(new RegExp(`Luna ${testInfo.project.name}`)).check();
  await page.getByLabel(new RegExp(`Terra ${testInfo.project.name}`)).check();
  await page.getByRole("button",{name:"So sánh",exact:true}).click();
  await expect(page.getByText("1 câu có review",{exact:false})).toBeVisible();
  await page.getByRole("button",{name:"Lọc chi tiết Factual QA"}).click();
  await expect(page.getByRole("combobox",{name:"Danh mục",exact:true})).toHaveValue("Factual QA");
  await expect(page.getByText("1 câu có review",{exact:false})).toBeVisible();
  await page.screenshot({path:`../reports/eval-v11-comparison-${testInfo.project.name}.png`,fullPage:true});
  await page.getByRole("button",{name:/80\/100/}).first().click();
  await expect(page.getByLabel("Evidence Inspector")).toBeVisible();
  await expect(page.getByText("Not captured — không có evidence snapshot.")).toBeVisible();
  await expect(page.getByRole("button", {name:"Đóng"})).toBeFocused();
  await page.keyboard.press("Shift+Tab");
  await expect(page.getByRole("button", {name:"Đóng"})).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(page.getByRole("button",{name:/80\/100/}).first()).toBeFocused();
  await page.getByRole("navigation").getByRole("button",{name:"Dữ liệu & Backup"}).click();
  await page.getByLabel("Chọn JSON, JSONL hoặc CSV").setInputFiles({name:"bad.jsonl",mimeType:"application/json",buffer:Buffer.from('{"bad":\n')});
  await page.getByRole("button",{name:"Kiểm tra trước khi nhập"}).click();
  await expect(page.getByText(/Dòng 1: Invalid JSON/)).toBeVisible();
  await expect(page.getByRole("button",{name:"Xác nhận nhập toàn bộ"})).toBeDisabled();
});
