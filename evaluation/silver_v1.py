"""Freeze Codex SILVER V1, split by primary source, and derive grounded RAG-SFT.

Generated datasets are local and Git-ignored. Run ``python -m evaluation.silver_v1 all``.
No model is loaded and no question or historical claim is generated by this tool.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from app.rag.response_modes import MODE_INSTRUCTIONS, sft_system_instruction
from evaluation.annotation.codex_batch import (
    DIFFICULTY_QUOTA, MASTER, WORKSPACE, ReadOnlyCorpus, validate_record,
)
from evaluation.annotation.policy import duplicate_pairs, fold
from evaluation.schema import Question

SEED = 42
COUNT = 3000
CANONICAL = Path("evaluation/datasets/v1_silver/questions_3000.jsonl")
SPLIT_DIR = Path("evaluation/datasets/v1_silver/splits/v1_seed42")
SFT_DIR = Path("training/datasets/vn_history_rag_sft_v1")
INDEX_MANIFEST = Path("artifacts/corpus_v1/retrieval/index_manifest.json")
SPLITS = ("train", "validation", "test")
RATIOS = {"train": 0.8, "validation": 0.1, "test": 0.1}
MODES = tuple(MODE_INSTRUCTIONS)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for part in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(part)
    return digest.hexdigest()


def json_lines(path: Path) -> list[dict[str, Any]]:
    return [json.loads(line) for line in path.open(encoding="utf-8") if line.strip()]


def encoded_json(value: Any) -> bytes:
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"),
                       allow_nan=False) + "\n").encode("utf-8")


def write_frozen(path: Path, data: bytes) -> None:
    """Create once; a rerun may verify bytes but cannot silently change a freeze."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        if path.read_bytes() != data:
            raise RuntimeError(f"Frozen output differs: {path}")
        return
    temp = path.with_name(path.name + f".partial-{os.getpid()}")
    with temp.open("xb") as handle:
        handle.write(data)
        handle.flush()
        os.fsync(handle.fileno())
    if path.exists():
        temp.unlink()
        if path.read_bytes() != data:
            raise RuntimeError(f"Frozen output differs: {path}")
        return
    os.replace(temp, path)


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    write_frozen(path, b"".join(encoded_json(row) for row in rows))


def _ids(rows: list[dict[str, Any]]) -> list[str]:
    return [row["id"] for row in rows]


def validate_source_batches(corpus: ReadOnlyCorpus, workspace: Path = WORKSPACE,
                            master: Path = MASTER) -> list[dict[str, Any]]:
    batch_paths = sorted((workspace / "batches").glob("batch_[0-9][0-9].jsonl"))
    expected = [f"batch_{number:02d}.jsonl" for number in range(1, 61)]
    if [path.name for path in batch_paths] != expected:
        raise ValueError("Expected exactly 60 contiguous completed batch files")
    rows = json_lines(master)
    if len(rows) != COUNT or _ids(rows) != [f"vn_hist_silver_{i:04d}" for i in range(1, COUNT + 1)]:
        raise ValueError("Master is not the exact 3000-record ID sequence")
    for batch_number, batch_path in enumerate(batch_paths, 1):
        batch = json_lines(batch_path)
        audit = json_lines(batch_path.with_name(f"batch_{batch_number:02d}.audit.jsonl"))
        if len(batch) != 50 or len(audit) != 50 or batch != rows[(batch_number-1)*50:batch_number*50]:
            raise ValueError(f"Completed batch {batch_number} disagrees with master")
        if Counter(row["difficulty"] for row in batch) != DIFFICULTY_QUOTA:
            raise ValueError(f"Completed batch {batch_number} violates difficulty quota")
        for record, evidence in zip(batch, audit, strict=True):
            Question.model_validate(record)
            validate_record(record, evidence, corpus)
    exact, near = duplicate_pairs(rows)
    if exact or near:
        raise ValueError(f"Canonical duplicate questions: exact={len(exact)}, near={len(near)}")
    return rows


def freeze(corpus: ReadOnlyCorpus, canonical: Path = CANONICAL) -> list[dict[str, Any]]:
    rows = validate_source_batches(corpus)
    # Preserve the finalized master byte-for-byte, including key order and whitespace.
    write_frozen(canonical, MASTER.read_bytes())
    if json_lines(canonical) != rows:
        raise RuntimeError("Canonical freeze changed finalized records")
    write_frozen(WORKSPACE / "frozen_v1.json", encoded_json({
        "dataset": "VN History SILVER Dataset V1", "completed_batches": 60,
        "canonical_count": COUNT, "canonical_sha256": sha256(canonical),
        "no_further_batches": True,
    }))
    return rows


def primary_source(row: dict[str, Any]) -> str:
    sources = row.get("relevant_source_ids") or []
    if not sources:
        # Stable fallback for a future evidence-free unanswerable record.
        return f"unlinked:{row['id']}"
    return sources[0]


def distribution(rows: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "difficulty": dict(sorted(Counter(row.get("difficulty") for row in rows).items())),
        "category": dict(sorted(Counter(row.get("category") for row in rows).items())),
        "question_type": dict(sorted(Counter(row.get("question_type") for row in rows).items())),
        "answerable": dict(sorted(Counter(str(row.get("answerable")) for row in rows).items())),
        "in_domain": dict(sorted(Counter(str(row.get("in_domain")) for row in rows).items())),
    }


def group_aware_split(rows: list[dict[str, Any]], seed: int = SEED) -> dict[str, list[dict[str, Any]]]:
    """Deterministic greedy stratification without dividing primary-source groups."""
    groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        groups[primary_source(row)].append(row)
    ordered = sorted(groups)
    random.Random(seed).shuffle(ordered)
    # Assign the very rare unanswerable groups first so validation and test
    # each have a chance to exercise abstention without splitting a source.
    ordered.sort(key=lambda key: (not any(row.get("answerable") is False
                                         for row in groups[key]), -len(groups[key])))
    totals = distribution(rows)
    targets = {split: len(rows) * RATIOS[split] for split in SPLITS}
    allocations: dict[str, list[dict[str, Any]]] = {split: [] for split in SPLITS}
    counters = {split: {field: Counter() for field in totals} for split in SPLITS}
    sizes = Counter()
    for group in ordered:
        sample = groups[group]
        current = distribution(sample)
        options = []
        for split in SPLITS:
            target = targets[split]
            # The overall count dominates; each distribution term adds a
            # smaller penalty for under/over-representing a label.
            before = (sizes[split] - target) ** 2 / target
            after = (sizes[split] + len(sample) - target) ** 2 / target
            cost = 3.0 * (after - before)
            for field, global_counts in totals.items():
                weight = (1.5 if field == "answerable" else
                          0.30 if field in {"difficulty", "category"} else 0.12)
                for label, n in current[field].items():
                    expected = global_counts[label] * RATIOS[split]
                    have = counters[split][field][label]
                    cost += weight * (((have+n-expected)**2 - (have-expected)**2) / max(1.0, expected))
            options.append((cost, SPLITS.index(split), split))
        split = min(options)[2]
        allocations[split].extend(sample)
        sizes[split] += len(sample)
        for field in totals:
            counters[split][field].update(current[field])
    for split in SPLITS:
        allocations[split].sort(key=lambda row: row["id"])
    return allocations


def validate_split(rows: list[dict[str, Any]], assignments: dict[str, list[dict[str, Any]]]) -> None:
    canonical = {row["id"]: row for row in rows}
    seen: set[str] = set()
    source_owner: dict[str, str] = {}
    for split in SPLITS:
        for row in assignments[split]:
            identifier = row["id"]
            if identifier in seen or canonical.get(identifier) != row:
                raise ValueError(f"Split duplicate or changed canonical row: {identifier}")
            seen.add(identifier)
            source = primary_source(row)
            if source in source_owner and source_owner[source] != split:
                raise ValueError(f"Primary source split leakage: {source}")
            source_owner[source] = split
    if seen != set(canonical):
        raise ValueError("Split union differs from canonical IDs")


def leakage_report(assignments: dict[str, list[dict[str, Any]]], corpus: ReadOnlyCorpus) -> dict[str, Any]:
    source_sets = {split: {source for row in assignments[split]
                           for source in row.get("relevant_source_ids") or []} for split in SPLITS}
    primary_sets = {split: {primary_source(row) for row in assignments[split]} for split in SPLITS}
    document_sets: dict[str, set[str]] = {split: set() for split in SPLITS}
    for split in SPLITS:
        for row in assignments[split]:
            for chunk_id in row.get("relevant_chunk_ids") or []:
                chunk = corpus.chunk(chunk_id)
                if chunk is None:
                    raise ValueError(f"Unknown chunk in split audit: {chunk_id}")
                if chunk.get("document_id"):
                    document_sets[split].add(chunk["document_id"])
    all_rows = [(split, row) for split in SPLITS for row in assignments[split]]
    by_id = {row["id"]: split for split, row in all_rows}
    exact, near = duplicate_pairs([row for _, row in all_rows])
    cross_exact = [(a,b) for a,b in exact if by_id[a] != by_id[b]]
    cross_near = [(a,b) for a,b in near if by_id[a] != by_id[b]]
    overlaps = {}
    for i, left in enumerate(SPLITS):
        for right in SPLITS[i+1:]:
            name = f"{left}_vs_{right}"
            overlaps[name] = {
                "primary_sources": len(primary_sets[left] & primary_sets[right]),
                "all_sources": len(source_sets[left] & source_sets[right]),
                "secondary_only_sources": len((source_sets[left] & source_sets[right]) -
                                              (primary_sets[left] & primary_sets[right])),
                "documents": len(document_sets[left] & document_sets[right]),
            }
    return {"id_intersections": {f"{a}_vs_{b}": len(set(_ids(assignments[a])) &
                                                       set(_ids(assignments[b])))
                                  for i,a in enumerate(SPLITS) for b in SPLITS[i+1:]},
            "cross_split_exact_questions": cross_exact,
            "cross_split_near_questions": cross_near,
            "source_and_document_overlap": overlaps,
            "note": "Primary source groups are disjoint. Secondary source/document overlap is reported, not hidden."}


def split(rows: list[dict[str, Any]], corpus: ReadOnlyCorpus,
          directory: Path = SPLIT_DIR) -> dict[str, list[dict[str, Any]]]:
    assignments = group_aware_split(rows)
    validate_split(rows, assignments)
    report = leakage_report(assignments, corpus)
    for name in SPLITS:
        write_jsonl(directory / f"{name}.jsonl", assignments[name])
    write_frozen(directory / "leakage_report.json", encoded_json(report))
    manifest = {
        "dataset_name": "VN History SILVER Dataset V1", "dataset_version": "1.0-3000",
        "canonical_dataset_path": CANONICAL.as_posix(),
        "canonical_dataset_sha256": sha256(CANONICAL), "seed": SEED,
        "split_strategy": "deterministic greedy group-aware stratification",
        "grouping_key": "first relevant_source_id; unlinked records use their ID",
        "ratios": RATIOS,
        "counts": {name: len(assignments[name]) for name in SPLITS},
        "ids": {name: _ids(assignments[name]) for name in SPLITS},
        "distributions": {name: distribution(assignments[name]) for name in SPLITS},
        "split_sha256": {name: sha256(directory / f"{name}.jsonl") for name in SPLITS},
        "leakage_report_sha256": sha256(directory / "leakage_report.json"),
    }
    write_frozen(directory / "split_manifest.json", encoded_json(manifest))
    return assignments


def load_frozen_split(directory: Path = SPLIT_DIR) -> dict[str, list[dict[str, Any]]]:
    manifest_path = directory / "split_manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest["canonical_dataset_sha256"] != sha256(CANONICAL) or manifest["seed"] != SEED:
        raise ValueError("Frozen split provenance changed")
    assignments = {name: json_lines(directory / f"{name}.jsonl") for name in SPLITS}
    for name in SPLITS:
        if sha256(directory / f"{name}.jsonl") != manifest["split_sha256"][name]:
            raise ValueError(f"Frozen {name} file hash changed")
        if _ids(assignments[name]) != manifest["ids"][name]:
            raise ValueError(f"Frozen {name} IDs changed")
        if len(assignments[name]) != manifest["counts"][name] or \
           distribution(assignments[name]) != manifest["distributions"][name]:
            raise ValueError(f"Frozen {name} distribution changed")
    if sha256(directory / "leakage_report.json") != manifest["leakage_report_sha256"]:
        raise ValueError("Frozen leakage report hash changed")
    validate_split(json_lines(CANONICAL), assignments)
    return assignments


def assign_modes(ids: list[str], *, seed: int = SEED) -> dict[str, str]:
    ordered = sorted(ids)
    random.Random(seed).shuffle(ordered)
    return {identifier: MODES[index % len(MODES)] for index, identifier in enumerate(ordered)}


def extra_modes(base: dict[str, str], count: int = 600, *, seed: int = SEED) -> dict[str, str]:
    """At most one second mode per ID; preserve balanced mode totals."""
    if count % len(MODES):
        raise ValueError("Extra variant target must divide evenly by mode")
    by_mode: dict[str, list[str]] = {mode: [] for mode in MODES}
    for identifier, mode in base.items():
        by_mode[mode].append(identifier)
    chosen = {}
    for index, mode in enumerate(MODES):
        identifiers = sorted(by_mode[mode])
        random.Random(seed + index + 1).shuffle(identifiers)
        if len(identifiers) < count // len(MODES):
            raise ValueError("Not enough canonical IDs for balanced variants")
        target_mode = MODES[(index + 1) % len(MODES)]
        for identifier in identifiers[:count // len(MODES)]:
            chosen[identifier] = target_mode
    return chosen


def sft_answer(record: dict[str, Any], mode: str) -> str:
    """Conservative presentation transform using only reviewed SILVER facts.

    It never discards the canonical answer. Detailed targets restate its audited
    atomic facts for clarity; simple lookup answers remain short in every mode.
    """
    answer = record["gold_answer"].strip()
    facts = [fact.strip() for fact in record.get("required_facts") or []]
    if not record.get("answerable"):
        return answer
    if mode == "concise":
        return answer
    if mode == "standard":
        if len(answer.split()) <= 7 and len(facts) == 1:
            return facts[0]
        return answer
    if mode == "detailed":
        if len(facts) == 1:
            return facts[0] if len(answer.split()) <= 7 else answer
        # Add only a small number of audited details that are genuinely absent
        # from the canonical answer. Repeating every required fact would train
        # the model to pad answers without adding information.
        covered = set(fold(answer).split())
        additions = []
        for fact in facts:
            tokens = set(fold(fact).split())
            novel = tokens - covered
            if len(novel) >= 3 and len(novel) / max(1, len(tokens)) >= 0.4:
                additions.append(fact)
                covered.update(tokens)
            if len(additions) == 2:
                break
        return f"{answer}\n\nChi tiết liên quan: {' '.join(additions)}" if additions else answer
    raise ValueError(f"Unknown response mode: {mode}")


def sft_messages(record: dict[str, Any], mode: str, corpus: ReadOnlyCorpus) -> list[dict[str, str]]:
    sections = []
    for chunk_id in record.get("relevant_chunk_ids") or []:
        chunk = corpus.chunk(chunk_id)
        if chunk is None or chunk.get("source_id") not in record.get("relevant_source_ids", []):
            raise ValueError(f"SFT context source mismatch: {chunk_id}")
        # No truncation, synthetic context, or source-text paraphrasing.
        sections.append(f"[{chunk_id}] {chunk['title']}\n{chunk['text']}")
    context = "\n\n".join(sections) if sections else "Không có nguồn phù hợp."
    return [
        {"role": "system", "content": sft_system_instruction(mode)},
        {"role": "user", "content": f"Câu hỏi: {record['question']}\n\nNguồn được truy xuất:\n{context}"},
        {"role": "assistant", "content": sft_answer(record, mode)},
    ]


def sft_row(record: dict[str, Any], mode: str, corpus: ReadOnlyCorpus) -> dict[str, Any]:
    if mode not in MODES:
        raise ValueError(mode)
    return {
        "id": f"{record['id']}:{mode}", "canonical_id": record["id"],
        "response_mode": mode, "messages": sft_messages(record, mode, corpus),
        "difficulty": record["difficulty"], "category": record["category"],
        "question_type": record.get("question_type"),
        "relevant_chunk_ids": record.get("relevant_chunk_ids") or [],
        "relevant_source_ids": record.get("relevant_source_ids") or [],
        "annotation_origin": "automatic", "dataset_tier": "SILVER",
    }


def build_sft(assignments: dict[str, list[dict[str, Any]]],
              corpus: ReadOnlyCorpus, *, seed: int = SEED,
              extra_count: int = 600) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    train = {row["id"]: row for row in assignments["train"]}
    validation = {row["id"]: row for row in assignments["validation"]}
    base = assign_modes(list(train), seed=seed)
    additional = extra_modes(base, extra_count, seed=seed)
    train_rows = [sft_row(train[identifier], mode, corpus)
                  for identifier, mode in base.items()]
    train_rows.extend(sft_row(train[identifier], mode, corpus)
                      for identifier, mode in additional.items())
    train_rows.sort(key=lambda row: (row["canonical_id"], MODES.index(row["response_mode"])))
    validation_modes = assign_modes(list(validation), seed=seed + 1000)
    validation_rows = [sft_row(validation[identifier], mode, corpus)
                       for identifier, mode in validation_modes.items()]
    validation_rows.sort(key=lambda row: row["canonical_id"])
    validate_sft(assignments, train_rows, validation_rows, corpus)
    return train_rows, validation_rows


def validate_sft(assignments: dict[str, list[dict[str, Any]]], train: list[dict[str, Any]],
                 validation: list[dict[str, Any]], corpus: ReadOnlyCorpus) -> dict[str, Any]:
    train_source = {row["id"]: row for row in assignments["train"]}
    validation_source = {row["id"]: row for row in assignments["validation"]}
    test_ids = set(_ids(assignments["test"]))
    per_id = Counter()
    pairs = set()
    for part, sft_rows, source in (("train", train, train_source),
                                  ("validation", validation, validation_source)):
        for item in sft_rows:
            identifier = item.get("canonical_id")
            mode = item.get("response_mode")
            if identifier not in source or identifier in test_ids or mode not in MODES:
                raise ValueError(f"{part} SFT leakage or invalid mode: {identifier}")
            pair = (part, identifier, mode)
            if pair in pairs or item.get("id") != f"{identifier}:{mode}":
                raise ValueError(f"Duplicate/invalid SFT variant: {pair}")
            pairs.add(pair)
            if part == "train":
                per_id[identifier] += 1
                if per_id[identifier] > 2:
                    raise ValueError(f"More than two variants: {identifier}")
            # Reconstruct exact chat messages from the real selected chunks.
            if item.get("messages") != sft_messages(source[identifier], mode, corpus):
                raise ValueError(f"Ungrounded or changed SFT messages: {identifier}:{mode}")
            if item.get("annotation_origin") != "automatic" or item.get("dataset_tier") != "SILVER":
                raise ValueError("SFT provenance must remain SILVER")
    if set(per_id) != set(train_source) or len(validation) != len(validation_source):
        raise ValueError("SFT canonical coverage disagrees with the frozen split")
    if {row["canonical_id"] for row in validation} != set(validation_source):
        raise ValueError("Validation SFT must represent each validation ID exactly once")
    return {
        "train_rows": len(train), "unique_train_ids": len(per_id),
        "train_variants_per_id": {str(k): v for k, v in sorted(Counter(per_id.values()).items())},
        "train_response_modes": dict(sorted(Counter(row["response_mode"] for row in train).items())),
        "validation_rows": len(validation),
        "validation_response_modes": dict(sorted(Counter(row["response_mode"] for row in validation).items())),
        "test_ids_in_sft": 0, "validation_ids_in_train_sft": 0,
    }


def derive(assignments: dict[str, list[dict[str, Any]]], corpus: ReadOnlyCorpus,
           directory: Path = SFT_DIR) -> dict[str, Any]:
    index_manifest = json.loads(INDEX_MANIFEST.read_text(encoding="utf-8"))
    if index_manifest["corpus_sha256"] != corpus.sha256 or \
       index_manifest["corpus_chunk_count"] != corpus.count:
        raise ValueError("Corpus and index manifest identity mismatch")
    train, validation = build_sft(assignments, corpus)
    stats = validate_sft(assignments, train, validation, corpus)
    write_jsonl(directory / "train_sft.jsonl", train)
    write_jsonl(directory / "validation_sft.jsonl", validation)
    write_frozen(directory / "stats.json", encoded_json(stats))
    manifest = {
        "dataset_name": "VN History RAG-SFT V1", "seed": SEED,
        "canonical_dataset_path": CANONICAL.as_posix(),
        "canonical_dataset_sha256": sha256(CANONICAL),
        "split_manifest_path": (SPLIT_DIR / "split_manifest.json").as_posix(),
        "split_manifest_sha256": sha256(SPLIT_DIR / "split_manifest.json"),
        "train_sft_sha256": sha256(directory / "train_sft.jsonl"),
        "validation_sft_sha256": sha256(directory / "validation_sft.jsonl"),
        "corpus_path": corpus.corpus.as_posix(), "corpus_sha256": corpus.sha256,
        "corpus_chunk_count": corpus.count,
        "ordered_chunk_id_sha256": index_manifest["ordered_chunk_id_sha256"],
        "index_manifest_sha256": sha256(INDEX_MANIFEST),
        "annotation_provenance": "Codex-generated SILVER; no human GOLD claim",
        "generation_provenance": "deterministic fact-preserving presentation; no model call",
        "context_policy": "all selected relevant chunks in canonical order, verbatim and untruncated",
        "response_mode_instructions": MODE_INSTRUCTIONS,
        "max_variants_per_train_id": 2,
        "train_rows": stats["train_rows"],
        "unique_canonical_train_ids": stats["unique_train_ids"],
        "validation_rows": stats["validation_rows"],
        "training_augmentation_policy": "TRAIN only; no validation or test answers used",
    }
    write_frozen(directory / "manifest.json", encoded_json(manifest))
    return stats


def validate_all(corpus: ReadOnlyCorpus) -> dict[str, Any]:
    source = validate_source_batches(corpus)
    if CANONICAL.read_bytes() != MASTER.read_bytes():
        raise ValueError("Frozen canonical dataset is not byte-identical to finalized master")
    marker = json.loads((WORKSPACE / "frozen_v1.json").read_text(encoding="utf-8"))
    if marker.get("canonical_sha256") != sha256(CANONICAL) or \
       marker.get("canonical_count") != COUNT or \
       marker.get("completed_batches") != 60 or not marker.get("no_further_batches"):
        raise ValueError("Codex SILVER V1 freeze marker is invalid")
    assignments = load_frozen_split()
    if group_aware_split(source) != assignments:
        raise ValueError("Frozen source grouping/seed is not reproducible")
    expected_report = leakage_report(assignments, corpus)
    if json.loads((SPLIT_DIR / "leakage_report.json").read_text(encoding="utf-8")) != expected_report:
        raise ValueError("Leakage report differs from split contents")
    train = json_lines(SFT_DIR / "train_sft.jsonl")
    validation = json_lines(SFT_DIR / "validation_sft.jsonl")
    stats = validate_sft(assignments, train, validation, corpus)
    manifest = json.loads((SFT_DIR / "manifest.json").read_text(encoding="utf-8"))
    if manifest["canonical_dataset_sha256"] != sha256(CANONICAL) or \
       manifest["split_manifest_sha256"] != sha256(SPLIT_DIR / "split_manifest.json") or \
       manifest["train_sft_sha256"] != sha256(SFT_DIR / "train_sft.jsonl") or \
       manifest["validation_sft_sha256"] != sha256(SFT_DIR / "validation_sft.jsonl") or \
       manifest["corpus_sha256"] != corpus.sha256 or \
       manifest["index_manifest_sha256"] != sha256(INDEX_MANIFEST):
        raise ValueError("SFT manifest provenance or file hash mismatch")
    if stats != json.loads((SFT_DIR / "stats.json").read_text(encoding="utf-8")):
        raise ValueError("SFT statistics changed")
    return {"canonical_count": len(source), "canonical_sha256": sha256(CANONICAL),
            "split_counts": {name: len(assignments[name]) for name in SPLITS},
            "sft": stats, "split_leakage": expected_report}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("freeze", "split", "derive", "validate", "all"))
    args = parser.parse_args(argv)
    corpus = ReadOnlyCorpus()
    try:
        if args.action in {"freeze", "all"}:
            freeze(corpus)
        if args.action in {"split", "all"}:
            if not CANONICAL.is_file():
                raise FileNotFoundError(CANONICAL)
            split(json_lines(CANONICAL), corpus)
        if args.action in {"derive", "all"}:
            derive(load_frozen_split(), corpus)
        result = validate_all(corpus) if args.action in {"validate", "all"} else {
            "action": args.action, "canonical_path": CANONICAL.as_posix()}
        print(json.dumps(result, ensure_ascii=False, indent=2))
    finally:
        corpus.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
